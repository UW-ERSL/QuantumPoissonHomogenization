def check_full_unitary() -> None:
    """Sec. 3.8: encoding error delta of U_V in 42 cases, delta <= 6 N 2^-F, and Prop. gate (iii)."""
    print("----- output --------------------------------------------------")
    print(f"{'N':>4} {'F':>3} {'delta':>10} {'delta 2^F/N':>11} {'gap':>8} {'ok':>3}")
    worst = 0.0
    for n in range(2, 9):
        for F in (12, 16, 20, 24, 28, 32):
            delta, chk = full_error(n, F, check_unitary=n <= 4)
            N = 2 ** n
            c = delta * 2.0 ** F / N
            worst = max(worst, c)
            ok = (c <= inversion.C_BOUND and chk["work_bits_left_set"] == 0 and chk["inputs_restored"]
                  and chk["zero_mode_outside"] and chk["exact_unitary_gap"] < 1e-6)
            print(f"{N:4d} {F:3d} {delta:10.2e} {c:11.2f} {chk['exact_unitary_gap']:8.1e} "
                  f"{'yes' if ok else 'NO':>3}", flush=True)
            assert ok
    print(f"largest delta 2^F / N over all cases: {worst:.2f}")


def check_qsvt_degree() -> None:
    """Sec. 3.7: degree and sup norm of the odd QSVT inverse polynomial, against their bounds."""
    def T(t, z):
        z = np.asarray(z, float)
        out = np.empty_like(z)
        i = np.abs(z) <= 1
        out[i] = np.cos(t * np.arccos(z[i]))
        out[~i] = np.sign(z[~i]) ** t * np.cosh(t * np.arccosh(np.abs(z[~i])))
        return out

    print(f"{'rho':>7} {'eps_p':>6} {'d':>7} {'bound':>7} {'C/rho':>6} {'bound':>6} {'argmax*rho':>10}")
    x = np.linspace(1e-12, 1.0, 4_000_001)
    for rho in (1.5, 10, 100, 1e3, 1e4):
        for eps_p in (1e-3, 1e-6):
            a = 1 / rho ** 2
            s = (1 + a) / (1 - a)
            t = int(np.ceil(np.arccosh(1 / eps_p) / np.arccosh(s)))
            r = T(t, (1 + a - 2 * x ** 2) / (1 - a)) / np.cosh(t * np.arccosh(s))
            q = (1 - r) / x
            k = np.argmax(np.abs(q))
            Cb = max(1 + eps_p, np.sqrt(0.5 * np.log(2 / eps_p) + 1 / rho))
            print(f"{rho:7g} {eps_p:6.0e} {2 * t - 1:7d} {rho * np.log(2 / eps_p) + 1:7.0f} "
                  f"{abs(q[k]) / rho:6.3f} {Cb:6.3f} {x[k] * rho:10.3f}")


def check_square() -> None:
    """Sec. 3.6: condition numbers of K^chi and M, and the gate-level block against Mtilde (square)."""
    import time
    print("----- output --------------------------------------------------")
    a = inversion.alpha_check()
    print(f"alpha = 16/3 = {cells.ALPHA:.4f}; pyblockencode: {a if a is None else f'{a:.4f}'}")
    print(f"{'N':>3} {'rho':>7} {'kappa(K^chi)':>13} {'kappa(M)':>10} {'M min*rho':>10} {'M max':>8} {'s':>5}")
    for N in (8, 16, 32, 64):
        for rho in (1.5, 3.75, 10, 100, 1e4):
            t = time.time()
            r = inversion.spectra(N, rho)
            kK = cells.ALPHA / r["Kmin"]
            print(f"{N:3d} {rho:7g} {kK:13.1f} {r['kappaM']:10.6f} {r['Mmin'] * rho:10.6f} "
                  f"{r['Mmax']:8.6f} {time.time() - t:5.1f}", flush=True)
    for N in (8, 16):
        for F in (24, 32):
            r = prop4_check(N, 10.0, F)
            print({k: (f"{v:.3e}" if isinstance(v, float) else v) for k, v in r.items()}, flush=True)
    print("---------------------------------------------------------------")


def check_inverse() -> None:
    """Sec. 3.7: the inverse on four heat sources, exact Mtilde and the gate-level block."""
