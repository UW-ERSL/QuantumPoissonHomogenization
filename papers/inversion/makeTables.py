"""makeTables.py -- every table of the paper, written to tables/ as LaTeX.

    python makeTables.py                 all four tables (about 2 minutes)
    python makeTables.py inverse         just that one
    python makeTables.py checks          the checks of Secs. 2-3 and 5 quoted in the text (about 10 minutes)
    python makeTables.py listings        Listings 1-3, output compared with the paper (about 20 seconds)
    python makeTables.py --list          names and destinations

Each file holds only the `tabular`, so the surrounding `table` environment,
the caption and the label stay in main.tex where they can be edited:

    \\begin{table}[H]
    \\caption{...}
    \\label{tab:inverse}
    \\centering
    \\input{tables/inverse}
    \\end{table}

Every claim the text makes about a table is ASSERTED before the table is
written, so a table cannot go stale relative to the code. Scalar conduction,
contrast rho = 10 unless stated; the three test cells are those of cells.py.
The values the text quotes are printed after each table.
"""
